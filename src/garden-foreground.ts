import type { Point } from "./core.ts";

export interface PaintedForeground { id: string; y: number; points: Point[] }
// Traced on the original 1536 x 1024 illustration. These are object contours,
// not collision polygons: the open archways must never repaint their paving.
const scale = 900 / 1536;
function part(id: string, foot: number, outline: number[][]): PaintedForeground {
  return {id, y: foot * scale, points: outline.map(([x,y]) => ({x:x*scale,y:y*scale}))};
}

