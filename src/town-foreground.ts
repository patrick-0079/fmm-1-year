import type { Point } from "./core.ts";

export interface TownForeground {
  id: string;
  /** Ground depth of the posts; never the height of the flowers or crossbeam. */
  y: number;
  points: Point[];
}
const shape = (id: string, y: number, outline: number[][]): TownForeground => ({
  id, y, points: outline.map(([x, y]) => ({x, y})),
});

