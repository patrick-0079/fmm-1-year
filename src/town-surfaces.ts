function ribbon(nodes: number[][]): Point[] {
  const sides: Point[][] = [[], []];
  nodes.forEach(([x, y, radius], i) => {
    const a = nodes[Math.max(0, i - 1)],
      b = nodes[Math.min(nodes.length - 1, i + 1)];
    const length = Math.hypot(b[0] - a[0], b[1] - a[1]);
    const nx = -(b[1] - a[1]) / length,
      ny = (b[0] - a[0]) / length;
    sides[0].push({ x: x + nx * radius, y: y + ny * radius });
    sides[1].push({ x: x - nx * radius, y: y - ny * radius });
  });
  return [...sides[0], ...sides[1].reverse()];
}
