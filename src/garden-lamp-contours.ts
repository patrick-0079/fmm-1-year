// Source-pixel profiles traced on garden-lanes-v18.webp. Lantern light belongs
// inside the metal frame; the warm paving/green grass outside it must stay open.
// Each row is [last source y, inclusive left x, inclusive right x]. The base
// then follows the attached flowers and stone, clockwise back to the stem.
function lamp(top: number, rows: number[][], base: number[][]): number[][] {
  const left: number[][] = [], right: number[][] = [];
  let y = top;
  for (const [bottom, l, r] of rows) {
    left.push([l,y],[l,bottom+1]);
    right.push([r+1,y],[r+1,bottom+1]);
    y = bottom + 1;
  }
  return [...right,...base,...left.reverse()];
}

