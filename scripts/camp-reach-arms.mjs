export function reachArmArt(row, event, frame, design) {
  if (frame < 9 || frame > 14) return "";
  if (row === 0) return event === "bird" ? lavenderPerch(frame) : lavenderTouch(frame);
  const right = event === "jelly", cel = frame-9;
  const pose = (right ? jelly : bird)[cel];
  const short = row === 5 || row === 6, kimono = row === 8;
  const loose = [0,1,3,4].includes(row);
  const {x,y} = campEncounterContact(event,frame);
  const px = 72+4*x, py = 184+4*y, raised = frame >= 10 && frame <= 13;
  const hand = (fill,stroke,width) => `<g transform="translate(${px} ${py})">${draw((right?palm:perch)[cel],fill,stroke,width)}</g>`;
  const crease = right ? "M-5.6 3.6 Q-3.65 3.15 -2.1 2.2" : "M6.6 3.3 Q7.8 3.7 8.35 4.9";
  let result;
  if (short) {
    result = draw(pose.bare,skin,skinInk,1.2) + hand(skin,skinInk,1.05)
      + draw(pose.bare,skin,"none") + hand(skin,"none") + draw(pose.cap,design.sleeve,ink,1.4);
    const seam = right && raised ? "M98 132.8 Q101 132.5 103.5 127" :
      right ? "M97 136 Q100 134 101.5 132" : "M45 132 Q47 135 50 136.5";
    result += line(seam,row===5?"#dfd0b8":design.shade,1.15);
    if (!raised) result += hand(skin,skinInk,1.05);
  } else {
    result = draw(kimono ? pose.bell : loose ? pose.loose : pose.fitted, design.sleeve, ink,1.5)
      + line(pose.fold,design.shade,1.2) + shoulderTrim(row,right,raised) + hand(skin,skinInk,1.05);
  }
  result += `<g transform="translate(${px} ${py})">${line(crease,"#d5a092",.6)}</g>`;
  if (!short) {
    result += draw(pose.cuff,kimono?design.sleeve:design.cuff,ink,1)
      + line(pose.hem,kimono?"#b75a50":design.shade,.9);
  }
  return result;
}
