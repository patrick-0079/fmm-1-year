import { lstat, mkdir, readFile, readdir, rename, rm, writeFile } from "node:fs/promises";
import { join, dirname, relative, sep } from "node:path";
import { randomUUID } from "node:crypto";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";
import { placeMeadowStars } from "./place-meadow-stars.mjs";

const fields = new Set(["id", "name", "message", "shape", "sprite", "order", "position"]);
const shapes = new Set(["plain", "cross", "gold", "pink-fish"]);

async function starFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = [];
  for (const entry of entries) {
    if (entry.isFile() && /\.json$/i.test(entry.name)) paths.push(join(directory, entry.name));
    if (entry.isDirectory()) {
      const contents = await readdir(join(directory, entry.name), { withFileTypes: true });
      if (contents.some(child => child.isFile() && child.name === "star.json")) {
        paths.push(join(directory, entry.name, "star.json"));
      }
    }
  }
  return paths.sort();
}

function validate(star) {
  if (!star || typeof star !== "object" || Array.isArray(star)) throw new Error("每份 JSON 需要一颗星的对象");
  for (const key of Object.keys(star)) if (!fields.has(key)) throw new Error(`未知字段 ${key}`);
  if (typeof star.id !== "string" || !/^star-[a-z0-9]+(?:-[a-z0-9]+)*$/.test(star.id)) throw new Error("id 需要形如 star-my-star");
  if (typeof star.name !== "string" || !star.name.trim()) throw new Error("name 不能为空");
  if (star.message !== undefined && typeof star.message !== "string") throw new Error("message 需要是文字");
  if (star.shape !== undefined && !shapes.has(star.shape)) throw new Error(`未知造型 ${star.shape}`);
  if (star.sprite !== undefined && (typeof star.sprite !== "string" || /[\\/:#%?]/.test(star.sprite) || !/\.(png|webp)$/i.test(star.sprite))) {
    throw new Error("sprite 应填写同目录的 PNG 或 WebP 文件名，避开 #、% 和 ?。");
  }
  if (star.order !== undefined && (!Number.isSafeInteger(star.order) || star.order < 0)) throw new Error("order 需要是非负整数");
  if (star.position !== undefined && (!Number.isFinite(star.position?.x) || !Number.isFinite(star.position?.y))) throw new Error("position 需要同时填写数值 x 和 y");
}

async function checkSprite(file, name) {
  const path = join(dirname(file), name);
  if (!(await lstat(path)).isFile()) throw new Error(`${name} 应为同目录的普通图片文件。`);
  const image = sharp(await readFile(path));
  const metadata = await image.metadata();
  const format = name.toLowerCase().endsWith(".png") ? "png" : "webp";
  if (metadata.format !== format) throw new Error(`${name} 的图片格式与扩展名不匹配。`);
  const stats = await image.stats();
  if (!metadata.hasAlpha || stats.isOpaque || stats.channels.at(-1).max === 0) {
    throw new Error(`${name} 需要带有透明背景，且至少有一个可见像素。`);
  }
}

function assetPath(manifestPath, file) {
  const path = relative(dirname(manifestPath), file).split(sep).join("/");
  if (/[#%?]/.test(path)) throw new Error(`${path}: 文件路径请避开 #、% 和 ?；署名可以包含这些字符。`);
  return path.startsWith(".") ? path : "./" + path;
}

export async function scanStars(sourceDir, manifestPath) {
  const records = [];
  const ids = new Map();
  for (const file of await starFiles(sourceDir)) {
    try {
      const record = JSON.parse((await readFile(file, "utf8")).replace(/^\uFEFF/, ""));
      validate(record);
      if (record.sprite) await checkSprite(file, record.sprite);
      if (ids.has(record.id)) throw new Error(`id ${record.id} 与 ${ids.get(record.id)} 重复`);
      ids.set(record.id, file);
      records.push({ ...record, file });
    } catch (error) {
      throw new Error(`${relative(sourceDir, file)}: ${error.message}`, { cause: error });
    }
  }
  records.sort((a, b) => (a.order ?? Infinity) - (b.order ?? Infinity) || (a.id < b.id ? -1 : 1));
  const positions = placeMeadowStars(records);
  const imports = [];
  const rows = [];
  for (const [i, record] of records.entries()) {
    imports.push(`import star${i} from ${JSON.stringify(assetPath(manifestPath, record.file))} with { type: "json" };`);
    const {x, y} = positions.get(record.id);
    const sprite = record.sprite ? assetPath(manifestPath, join(dirname(record.file), record.sprite)) : undefined;
    const source = sprite ? `, sprite: new URL(${JSON.stringify(sprite + "?no-inline")}, import.meta.url).href` : "";
    rows.push(`  { record: star${i}, x: ${x}, y: ${y}${source} },`);
  }
  const manifest = ["// Generated by npm run scan:stars from ref/花海星星.", ...imports, "", "export const starIndex = [", ...rows, "] as const;", ""].join("\n");
  const previous = await readFile(manifestPath, "utf8").catch(error => { if (error.code !== "ENOENT") throw error; });
  if (manifest !== previous?.replaceAll("\r\n", "\n")) {
    await mkdir(dirname(manifestPath), { recursive: true });
    const temporary = `${manifestPath}.${randomUUID()}.tmp`;
    try {
      await writeFile(temporary, manifest);
      await rename(temporary, manifestPath);
    } finally { await rm(temporary, {force: true}); }
  }
  return positions;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const root = fileURLToPath(new URL("../", import.meta.url));
  const entries = await scanStars(join(root, "ref/花海星星"), join(root, "src/stars.generated.ts"));
  console.log(`花海星星已更新，共 ${entries.size} 颗。`);
}
