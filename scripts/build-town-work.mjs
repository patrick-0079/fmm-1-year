// Bake stationary hand and work poses from the actual painted residents. Run from the repository root:
// node --experimental-strip-types scripts/build-town-work.mjs
import sharp from "sharp";
import {writeFile} from "node:fs/promises";
import { fileURLToPath } from "node:url";
import {TOWN_NPCS,TOWN_FRAMES} from "../src/town-data.ts";
import {workCell as S,workFoot,workFrames,workBeat,workJoints,residentHeight} from "../src/town-work-poses.ts";

const root=new URL("../src/assets/",import.meta.url);
const width=S*workFrames, height=S*TOWN_NPCS.length;
const rgba=Buffer.alloc(width*height*4);
const landmarks={};
const file = name => fileURLToPath(new URL(name, root));
const clamp=x=>Math.min(1,Math.max(0,x));
const smooth=t=>{t=clamp(t);return t*t*(3-2*t);};
const squash=(offset,radius)=>{const t=Math.abs(offset/radius);return t>=1?0:(1-t*t)**2;};

async function portrait(n,row){
  const nominal=residentHeight(row), f=TOWN_FRAMES[n.sprite];
  let name="town-npcs.webp", rect=f, h=nominal*2, foot=1;
  if(n.appearance==="guest"){
    name="town-guests.webp";rect={x:n.sprite*128,y:0,w:128,h:128};foot=126/128;
  }else if(n.id==="radio-host"){
    // Her listening gesture grows out of the existing raised *left* palm.
    name="yeshenhua.webp";rect={x:1083,y:34,w:506,h:827};foot=823/827;
  }else if(n.id==="baker"){
    name="town-gestures.webp";rect={x:128,y:0,w:128,h:128};
  }
  const ph=Math.round(h), pw=Math.round(h*rect.w/rect.h);
  const pixels=await sharp(file(name)).extract({left:rect.x,top:rect.y,width:rect.w,height:rect.h})
    .ensureAlpha().resize(pw,ph,{fit:"fill",kernel:"lanczos3"}).raw().toBuffer();
  const cx=Math.round(S/2-pw/2),cy=Math.round(workFoot-ph*foot);
  const buf=Buffer.alloc(S*S*4);
  for(let y=0;y<ph;y++) pixels.copy(buf,((cy+y)*S+cx)*4,y*pw*4,(y+1)*pw*4);
  let left=S,top=S,right=0,bottom=0;
  for(let y=0;y<S;y++)for(let x=0;x<S;x++)if(buf[(y*S+x)*4+3]>130){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
  return {buf,left,top,w:right-left+1,h:bottom-top+1};
}

for(const [row,n] of TOWN_NPCS.entries()){
  const src=await portrait(n,row);
  landmarks[n.id]=[src.left,src.top,src.w,src.h];
  const joints=workJoints[n.id];
  for(let frame=0;frame<workFrames;frame++){
    const {lift,stroke}=workBeat(frame);
    function displacement(px,py){
      const x=(px-src.left)/src.w,y=(py-src.top)/src.h;
      let ox=0, oy=0;
      const gaze=(n.id==="walker"||n.id==="hop-keeper")?-1:1;
      const head=squash(x-.5,.59)*(1-smooth((y-.45)/.19));
      oy+=head*(lift*1.5*gaze);
      ox+=head*lift*.63;
      for(const [jx,jy,jdx,jdy,jrx,jry] of joints){
        const weight=squash(x-jx,jrx)*squash(y-jy,jry);
        const follow=lift+.14*stroke*(jx<.5?1:-1);
        ox+=weight*jdx*follow*src.w;
        oy+=weight*jdy*follow*src.h;
      }
      return [ox,oy];
    }
    for(let y=0;y<S;y++)for(let x=0;x<S;x++){
      const o=(((row*S+y)*width)+(frame*S+x))*4;
      // Invert the warp at the pixel centres. Bilinear colour reconstruction
      // uses premultiplied alpha to keep the painted, antialiased edges clean.
      let u=x,v=y;
      if(frame)for(let pass=0;pass<3;pass++){const d=displacement(u,v);u=x-d[0];v=y-d[1];}
      if(u<0||v<0||u>=S-1||v>=S-1)continue;
      const i=Math.floor(u),j=Math.floor(v),fx=u-i,fy=v-j;
      const neighbours=[[(j*S+i)*4,(1-fx)*(1-fy)],[(j*S+i+1)*4,fx*(1-fy)],
        [((j+1)*S+i)*4,(1-fx)*fy],[((j+1)*S+i+1)*4,fx*fy]];
      let alpha=0,r=0,g=0,b=0;
      for(const [at,weight] of neighbours){
        const a=src.buf[at+3]*weight;alpha+=a;r+=a*src.buf[at];g+=a*src.buf[at+1];b+=a*src.buf[at+2];
      }
      if(alpha>.5){rgba[o]=Math.round(r/alpha);rgba[o+1]=Math.round(g/alpha);rgba[o+2]=Math.round(b/alpha);rgba[o+3]=Math.round(alpha);}
    }
  }
}
await writeFile(file("town-work-poses.webp"),await sharp(rgba,{raw:{width,height,channels:4}}).webp({quality:81,alphaQuality:96,effort:5}).toBuffer());
const rows = Object.entries(landmarks).map(([id, bounds]) => `  ${JSON.stringify(id)}: [${bounds.join(", ")}],`);
await writeFile(new URL("../src/town-work-bounds.ts", import.meta.url),
  ["// Neutral bounds at twice the map scale. Generated by build-town-work.mjs.", "export const paintedBounds = {",
   ...rows, "} as const;", ""].join("\n"));
