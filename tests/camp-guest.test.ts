import test from "node:test";
import assert from "node:assert/strict";
import { CampGuest, campGuestStart, campGuestSeat } from "../src/camp-guest.ts";
import { canTravelBetween } from "../src/core.ts";
import { clickedInteraction, nearbyInteraction } from "../src/interaction.ts";
import { campLetterSpot, campSeat, meadowScene } from "../src/meadow-map.ts";
import { collectHandedLetter, handedLetters, mailboxLetters, readResidentStory } from "../src/resident-story.ts";
import { benchRest } from "../src/rest.ts";

const camp = meadowScene.spots.find(spot => spot.id === "meadow-camp")!;
const sheet = {naturalWidth: 256} as HTMLImageElement;
const sitting = () => benchRest("meadow", campSeat, camp.approach);

test("30 uninterrupted seconds of sitting bring the guest, who leaves an uncollected letter on the ground", () => {
  const world: ConstructorParameters<typeof CampGuest>[0] = {scene: "meadow", restState: sitting(), paused: false};
  const story = readResidentStory();
  const beforeVisit = mailboxLetters(story);
  let saves = 0;
  const guest = new CampGuest(world, () => story, () => { saves++; });
  guest.tick(.016, 10);
  guest.tick(.016, 39.999);
  assert.equal(story.patrickArrived, false);
  assert.deepEqual(guest.layers(sheet, false), []);
  world.restState = sitting();
  guest.tick(.016, 40);
  guest.tick(.016, 69.999);
  assert.equal(saves, 0, "standing before the guest arrives restarts the wait");
  guest.tick(.016, 70);
  assert.equal(story.patrickArrived, true);
  assert.equal(saves, 1);
  assert.equal(guest.layers(sheet, false)[0].y, campGuestStart.y);
  assert.equal(guest.layers(sheet, true)[0].y, campGuestSeat.y);
  assert.equal(guest.letterOnGround, false);
  guest.tick(1.75, 71.75);
  assert.equal(guest.letterOnGround, false);
  guest.tick(.45, 72.2);
  assert.equal(guest.letterOnGround, true);
  assert.deepEqual(mailboxLetters(story), beforeVisit);
  assert.ok(beforeVisit.every(({id}) => id !== handedLetters.patrick));
  assert.deepEqual(guest.layers(sheet, false).map(layer => layer.y), [campGuestSeat.y, campLetterSpot.y]);
  world.restState = null;
  guest.tick(.016, 72.216);
  assert.deepEqual(guest.layers(sheet, false).map(layer => layer.y), [campLetterSpot.y]);
  assert.ok(collectHandedLetter(story, handedLetters.patrick));
  assert.equal(guest.letterOnGround, false);
  world.restState = sitting();
  guest.tick(.016, 80);
  guest.tick(.016, 111);
  assert.deepEqual(guest.layers(sheet, false), []);
  assert.equal(saves, 1, "the guest never arrives twice in a save");
});

test("the guest waits for an active camp view and the dropped letter is reachable and clickable", () => {
  assert.ok(canTravelBetween(campGuestStart, campGuestSeat, meadowScene));
  assert.ok(canTravelBetween(camp.approach, campLetterSpot.approach, meadowScene));
  assert.equal(clickedInteraction({x: campLetterSpot.x, y: campLetterSpot.y - 5}, meadowScene.spots), campLetterSpot);
  assert.equal(nearbyInteraction(campLetterSpot.approach, meadowScene.spots), campLetterSpot);
  const world = {scene: "meadow" as const, restState: sitting(), paused: false};
  const story = readResidentStory();
  let saves = 0;
  const guest = new CampGuest(world, () => story, () => { saves++; });
  guest.tick(.016, 1);
  guest.tick(0, 31);
  world.paused = true;
  guest.tick(.016, 32);
  assert.equal(saves, 0);
  world.paused = false;
  guest.tick(.016, 33);
  assert.equal(saves, 1);
  assert.equal(guest.layers(sheet, false)[0].y, campGuestStart.y);
  guest.tick(1, 34);
  assert.equal(guest.layers(sheet, false)[0].y, campGuestSeat.y);
});

test("leaving during the one arrival or reloading still leaves only the unclaimed envelope", () => {
  const world: ConstructorParameters<typeof CampGuest>[0] = {scene:"meadow", restState:sitting(), paused:false};
  let story = readResidentStory();
  const guest = new CampGuest(world, () => story, () => {});
  guest.tick(.016, 10);
  guest.tick(.016, 40);
  assert.equal(guest.letterOnGround, false);
  world.restState = null;
  guest.tick(1, 41);
  assert.equal(guest.letterOnGround, false, "he can finish setting down the letter after the player stands");
  world.scene = "garden";
  guest.reset();
  assert.equal(guest.letterOnGround, false);
  assert.deepEqual(guest.layers(sheet, false), []);
  story = readResidentStory(JSON.parse(JSON.stringify(story)));
  const restored = new CampGuest(world, () => story, () => assert.fail("the arrival must not replay"));
  world.scene = "meadow";
  world.restState = sitting();
  restored.tick(.016, 50);
  restored.tick(.016, 85);
  assert.equal(restored.letterOnGround, true);
  assert.deepEqual(restored.layers(sheet, true).map(layer => layer.y), [campLetterSpot.y]);
});
